const REVERSE_TRANSLATIONS: Record<string, string> = Object.fromEntries(
  Object.entries(UI_TRANSLATIONS).map(([en, ar]) => [ar, en])
);

function preserveWhitespace(original: string, translated: string) {
  const start = original.match(/^\s*/)?.[0] ?? "";
  const end = original.match(/\s*$/)?.[0] ?? "";
  return start + translated.trim() + end;
}

export function translateUiText(value: string, language: UiLanguage) {
  if (!value.trim()) return value;
  const trimmed = value.trim();
  const translated =
    language === "ar"
      ? UI_TRANSLATIONS[trimmed]
      : REVERSE_TRANSLATIONS[trimmed];
  return translated ? preserveWhitespace(value, translated) : value;
}
